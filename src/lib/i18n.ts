export type Dict = { [K in keyof (typeof dict)["es"]]: string };
export function t(locale: string | null | undefined): Dict {
  return dict[locale === "en" ? "en" : "es"];
}

export function fmtDate(d: Date | null | undefined, locale: string, tz = "America/Guatemala", withTime = false): string {
  if (!d) return "—";
  return new Intl.DateTimeFormat(locale === "en" ? "en-US" : "es-GT", {
    dateStyle: "long",
    ...(withTime ? { timeStyle: "short" } : {}),
    timeZone: tz,
  }).format(d);
}
